#!/usr/bin/env python3
"""Phase 5: pack the painted hero pose frames into one atlas (fewer textures, batched draws).
Frames are packed untrimmed (AtlasTexture size == original frame size, so sprite offsets are
unchanged). Sources live in art_src/hero_frames/ (idle.png also stays in assets for Player.tscn).
Writes assets/sprites/hero/hero_poses_atlas.png and scripts/anim/hero_atlas.gd."""
from PIL import Image
import glob, os, json
SRC = "art_src/hero_frames"; PAD = 2; W = 1024
fs = sorted(glob.glob(SRC + "/*.png")) + ["assets/sprites/hero/idle.png"]
ims = [(os.path.basename(f)[:-4], Image.open(f).convert("RGBA")) for f in fs]
ims.sort(key=lambda t: -t[1].size[1])
x = y = rowh = 0; regions = {}
for n, im in ims:
	w, h = im.size
	if x + w > W: x = 0; y += rowh + PAD; rowh = 0
	regions[n] = [x, y, w, h]; x += w + PAD; rowh = max(rowh, h)
H = y + rowh
H = 1 << (H - 1).bit_length()
atlas = Image.new("RGBA", (W, H), (0, 0, 0, 0))
for n, im in ims: atlas.paste(im, tuple(regions[n][:2]))
atlas.save("assets/sprites/hero/hero_poses_atlas.png", optimize=True)
gd = ["## GENERATED by tools/gen_atlas.py — hero pose regions in hero_poses_atlas.png", "class_name HeroAtlas",
      'const ATLAS := preload("res://assets/sprites/hero/hero_poses_atlas.png")',
      "const REGIONS := " + json.dumps(regions, sort_keys=True), "static var _cache := {}",
      "static func textures() -> Dictionary:",
      "\tif _cache.is_empty():",
      "\t\tfor k in REGIONS:",
      "\t\t\tvar t := AtlasTexture.new(); t.atlas = ATLAS; var r: Array = REGIONS[k]",
      "\t\t\tt.region = Rect2(r[0], r[1], r[2], r[3]); _cache[k] = t",
      "\treturn _cache"]
open("scripts/anim/hero_atlas.gd", "w").write("\n".join(gd) + "\n")
print("atlas %dx%d, %d frames, %d bytes" % (W, H, len(ims), os.path.getsize("assets/sprites/hero/hero_poses_atlas.png")))
